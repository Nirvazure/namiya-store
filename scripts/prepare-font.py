"""Build local Source Han Serif CN fonts for the site's book typography.

Usage: python scripts/prepare-font.py /path/to/source-font-directory
The directory must contain SourceHanSerifCN-{Regular,Medium}.otf,
SourceHanSerif-OFL.txt and upstream-commit.txt from the official release branch.
Requires fonttools and brotli only when updating font assets.
"""
import hashlib
import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
source_dir = Path(sys.argv[1])
output = root / "public/fonts"
output.mkdir(parents=True, exist_ok=True)
text = "".join(
    file.read_text(encoding="utf-8")
    for folder, extension in [("app", "*.tsx"), ("components", "*.tsx"), ("domain", "*.ts")]
    for file in sorted((root / folder).rglob(extension))
)
common = {ord(char) for char in text} | set(range(32, 127)) | set(range(0x2000, 0x2070)) | set(range(0x3000, 0x3040))
regular = source_dir / "SourceHanSerifCN-Regular.otf"
medium = source_dir / "SourceHanSerifCN-Medium.otf"
with TTFont(regular) as font:
    available = set(font.getBestCmap())
    version = font["name"].getDebugName(5)
common &= available
extended = available - common


def build(source, filename, codepoints, family, style):
    font = TTFont(source, recalcTimestamp=False)
    options = subset.Options()
    options.flavor = "woff2"
    options.recalc_timestamp = False
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
    options.name_languages = [0x409]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    # Subsets use their own family name, preserving upstream copyright/license.
    postscript = family.replace(" ", "") + "-" + style
    names = {1: family, 2: style, 3: postscript, 4: f"{family} {style}", 6: postscript, 16: family, 17: style}
    for record in font["name"].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    if "CFF " in font:
        cff = font["CFF "].cff
        cff.fontNames = [postscript]
        cff.topDictIndex[0].FamilyName = family
        cff.topDictIndex[0].FullName = f"{family} {style}"
        cff.topDictIndex[0].Weight = style
    font.flavor = "woff2"
    font.save(output / filename)
    font.close()
    with TTFont(output / filename) as result:
        assert set(result.getBestCmap()) == codepoints, f"Incomplete font: {filename}"
    return {"file": filename, "glyphs": len(codepoints), "bytes": (output / filename).stat().st_size}


files = [
    build(regular, "namiya-book-regular.woff2", common, "Namiya Book", "Regular"),
    build(medium, "namiya-book-medium.woff2", common, "Namiya Book", "Medium"),
    build(regular, "namiya-book-extended.woff2", extended, "Namiya Book Extended", "Regular"),
]

# Restrict the extended face to missing characters so static copy loads only the
# small common face. Letters and generated replies retain upstream CJK coverage.
ranges = []
for codepoint in sorted(extended):
    if ranges and codepoint == ranges[-1][1] + 1:
        ranges[-1][1] = codepoint
    else:
        ranges.append([codepoint, codepoint])
unicode_range = ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in ranges)
(root / "app/book-font.css").write_text(
    "/* Generated by scripts/prepare-font.py. Keep this stylesheet in app. */\n"
    '@font-face {\n  font-family: "Namiya Book Extended";\n'
    '  src: url("/fonts/namiya-book-extended.woff2") format("woff2");\n'
    '  font-style: normal;\n  font-weight: 400;\n  font-display: swap;\n'
    f"  unicode-range: {unicode_range};\n}}\n", encoding="utf-8",
)
(output / "OFL.txt").write_bytes((source_dir / "SourceHanSerif-OFL.txt").read_bytes())
manifest = {
    "upstream": "https://github.com/adobe-fonts/source-han-serif",
    "sourceCommit": (source_dir / "upstream-commit.txt").read_text(encoding="utf-8-sig").strip(),
    "sourceVersion": version,
    "sourceSha256": {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in [regular, medium]},
    "files": files,
    "coveredCodepoints": len(available),
}
(output / "font-source.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print(json.dumps(manifest, ensure_ascii=False))
